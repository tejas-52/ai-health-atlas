# ─── Data loaders (cached) ───────────────────────────────────────
@st.cache_data(ttl=60)
def load_aggregated(districts=None, years=None, genders=None, age_groups=None):
    age_case = """
        CASE WHEN dem.age BETWEEN 0 AND 17 THEN '0-17'
             WHEN dem.age BETWEEN 18 AND 34 THEN '18-34'
             WHEN dem.age BETWEEN 35 AND 49 THEN '35-49'
             WHEN dem.age BETWEEN 50 AND 64 THEN '50-64'
             ELSE '65+' END
    """
    conds = ["1=1"]
    if districts:
        conds.append(f"d.name IN ({','.join(['?']*len(districts))})")
    if years:
        conds.append(f"dem.year IN ({','.join(['?']*len(years))})")
    if genders:
        conds.append(f"dem.gender IN ({','.join(['?']*len(genders))})")
    if age_groups:
        age_sub = []
        for ag in age_groups:
            m = {"0-17":"dem.age BETWEEN 0 AND 17","18-34":"dem.age BETWEEN 18 AND 34",
                 "35-49":"dem.age BETWEEN 35 AND 49","50-64":"dem.age BETWEEN 50 AND 64","65+":"dem.age >= 65"}
            age_sub.append(m[ag])
        conds.append(f"({' OR '.join(age_sub)})")

    params = list(districts or []) + list(years or []) + list(genders or []) + []
    sql = f"""
        SELECT d.name AS district_name, dem.year, dem.gender,
               {age_case} AS age_group,
               COUNT(dem.id) AS cohort_size,
               AVG(dem.income) AS avg_income,
               AVG(dem.life_expectancy) AS avg_life_expectancy,
               SUM(dem.employed)*100.0/COUNT(dem.id) AS employment_rate,
               SUM(epi.diabetes)*100.0/COUNT(dem.id) AS diabetes_rate,
               SUM(epi.heart_disease)*100.0/COUNT(dem.id) AS heart_disease_rate,
               SUM(epi.obesity)*100.0/COUNT(dem.id) AS obesity_rate,
               SUM(epi.smoking)*100.0/COUNT(dem.id) AS smoking_rate,
               SUM(epi.vaccinated)*100.0/COUNT(dem.id) AS vaccination_rate,
               AVG(epi.mental_health_index) AS avg_mental_health_index
        FROM demographics dem
        JOIN districts d ON dem.district_id = d.id
        JOIN epidemiology epi ON dem.id = epi.demographic_id
        WHERE {' AND '.join(conds)}
        GROUP BY district_name, year, gender, age_group
    """
    return query(sql, params)

@st.cache_data(ttl=60)
def load_env(districts=None, years=None):
    conds = ["1=1"]
    params = []
    if districts:
        conds.append(f"d.name IN ({','.join(['?']*len(districts))})")
        params += districts
    if years:
        conds.append(f"CAST(SUBSTR(e.date,1,4) AS INT) IN ({','.join(['?']*len(years))})")
        params += years
    sql = f"""
        SELECT d.name AS district_name,
               CAST(SUBSTR(e.date,1,4) AS INT) AS year,
               AVG(e.pm25) AS avg_pm25,
               AVG(e.temperature) AS avg_temp,
               AVG(e.green_space_pct) AS avg_green,
               AVG(e.noise_level_db) AS avg_noise,
               AVG(e.water_quality_index) AS avg_water
        FROM environmental e
        JOIN districts d ON e.district_id = d.id
        WHERE {' AND '.join(conds)}
        GROUP BY district_name, year
    """
    return query(sql, params)

@st.cache_data(ttl=60)
def load_hospitals():
    return query("""SELECT h.*, d.name AS district_name
                   FROM healthcare_resources h JOIN districts d ON h.district_id=d.id""")

@st.cache_data(ttl=60)
def load_districts():
    return query("SELECT name FROM districts")["name"].tolist()

# ─── KPI helper ─────────────────────────────────────────────────
def kpi(label, value, sub=""):
    st.markdown(f"""
    <div class='kpi-card'>
      <div class='kpi-label'>{label}</div>
      <div class='kpi-value'>{value}</div>
      <div class='kpi-sub'>{sub}</div>
    </div>""", unsafe_allow_html=True)

def w_avg(df, val_col, weight_col="cohort_size"):
    tot = df[weight_col].sum()
    return (df[val_col] * df[weight_col]).sum() / tot if tot > 0 else 0

