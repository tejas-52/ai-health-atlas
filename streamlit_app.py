# ─── AI Chatbot ─────────────────────────────────────────────────
def chatbot_answer(msg):
    ml = msg.lower()
    # Obesity
    if "obesity" in ml and ("highest" in ml or "most" in ml):
        r = query("""SELECT d.name, AVG(epi.obesity)*100 AS rate
                     FROM epidemiology epi JOIN demographics dem ON epi.demographic_id=dem.id
                     JOIN districts d ON dem.district_id=d.id GROUP BY d.name ORDER BY rate DESC LIMIT 1""")
        return f"**{r.iloc[0]['name']}** has the highest obesity rate at **{r.iloc[0]['rate']:.1f}%**."
    # Lowest income
    if "lowest income" in ml or "poorest" in ml:
        r = query("SELECT d.name, AVG(dem.income) AS inc FROM demographics dem JOIN districts d ON dem.district_id=d.id GROUP BY d.name ORDER BY inc ASC LIMIT 1")
        return f"**{r.iloc[0]['name']}** has the lowest avg income at **€{r.iloc[0]['inc']:,.0f}**."
    # Highest income
    if "highest income" in ml or "wealthiest" in ml or "richest" in ml:
        r = query("SELECT d.name, AVG(dem.income) AS inc FROM demographics dem JOIN districts d ON dem.district_id=d.id GROUP BY d.name ORDER BY inc DESC LIMIT 1")
        return f"**{r.iloc[0]['name']}** has the highest avg income at **€{r.iloc[0]['inc']:,.0f}**."
    # Hospitals / healthcare
    if "hospital" in ml or "healthcare" in ml or "access" in ml:
        r = query("SELECT d.name, COUNT(h.id) AS cnt, SUM(h.beds) AS beds, AVG(h.emergency_response_time_min) AS resp FROM districts d LEFT JOIN healthcare_resources h ON d.id=h.district_id GROUP BY d.name ORDER BY resp")
        lines = "\n".join([f"- **{row['name']}**: {int(row['cnt'])} facilities, {int(row['beds'] or 0)} beds, {row['resp']:.1f} min response" for _, row in r.iterrows()])
        return f"**Healthcare Access by District:**\n{lines}"
    # PM2.5 / pollution
    if "pm2.5" in ml or "pollution" in ml or "air" in ml:
        r = query("SELECT d.name, AVG(e.pm25) AS pm FROM environmental e JOIN districts d ON e.district_id=d.id GROUP BY d.name ORDER BY pm DESC")
        top = r.iloc[0]; bot = r.iloc[-1]
        return f"**{top['name']}** has the worst air quality (PM2.5: **{top['pm']:.1f} µg/m³**). **{bot['name']}** is cleanest (**{bot['pm']:.1f} µg/m³**)."
    # Vaccination
    if "vaccin" in ml:
        r = query("SELECT d.name, AVG(epi.vaccinated)*100 AS rate FROM epidemiology epi JOIN demographics dem ON epi.demographic_id=dem.id JOIN districts d ON dem.district_id=d.id GROUP BY d.name ORDER BY rate DESC")
        lines = "\n".join([f"- **{row['name']}**: {row['rate']:.1f}%" for _, row in r.iterrows()])
        return f"**Vaccination rates by district:**\n{lines}"
    # Compare two districts
    all_d = load_districts()
    found = [d for d in all_d if d.lower() in ml]
    if len(found) >= 2:
        r = query(f"""SELECT d.name, AVG(dem.income) AS income, AVG(dem.life_expectancy) AS life_exp,
                             AVG(epi.obesity)*100 AS obesity, AVG(epi.diabetes)*100 AS diabetes,
                             AVG(epi.smoking)*100 AS smoking, AVG(epi.vaccinated)*100 AS vac
                      FROM demographics dem JOIN epidemiology epi ON dem.id=epi.demographic_id
                      JOIN districts d ON dem.district_id=d.id
                      WHERE d.name IN ('{found[0]}','{found[1]}') GROUP BY d.name""")
        if len(r) == 2:
            a, b = r.iloc[0], r.iloc[1]
            return (f"### {a['name']} vs {b['name']}\n\n"
                    f"| Indicator | {a['name']} | {b['name']} |\n|---|---|---|\n"
                    f"| Avg Income | €{a['income']:,.0f} | €{b['income']:,.0f} |\n"
                    f"| Life Expectancy | {a['life_exp']:.1f} yrs | {b['life_exp']:.1f} yrs |\n"
                    f"| Obesity | {a['obesity']:.1f}% | {b['obesity']:.1f}% |\n"
                    f"| Diabetes | {a['diabetes']:.1f}% | {b['diabetes']:.1f}% |\n"
                    f"| Smoking | {a['smoking']:.1f}% | {b['smoking']:.1f}% |\n"
                    f"| Vaccination | {a['vac']:.1f}% | {b['vac']:.1f}% |")
    # Fallback
    return ("I can answer questions like:\n"
            "- *Which district has the highest obesity?*\n"
            "- *Compare Neustadt and Prohlis*\n"
            "- *What is air quality / PM2.5 like?*\n"
            "- *Which district has the best vaccination rate?*\n"
            "- *Which district is wealthiest?*")

